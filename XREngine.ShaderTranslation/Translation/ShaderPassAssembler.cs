using System.Text;
using System.Text.RegularExpressions;
using XREngine.ShaderTranslation.ShaderLab;

namespace XREngine.ShaderTranslation.Translation;

/// <summary>
/// Builds the HLSL translation unit for one stage of one pass.
/// </summary>
/// <remarks>
/// The unit holds, in order: the platform and pass defines, the selected keywords, the legacy conversion
/// include, Unity's implicit includes for <c>CGPROGRAM</c>, the include blocks of the shader, subshader, and pass, and the program.
/// Line directives map compiler diagnostics back to the <c>.shader</c> file. <c>#pragma</c> lines are
/// blanked, because translation reads them separately; blank lines keep the line numbers.
/// </remarks>
public static partial class ShaderPassAssembler
{
    /// <summary>Gets the <c>UNITY_VERSION</c> value. It matches Unity 2022.3, the common avatar editor version.</summary>
    public const int UnityVersion = 202231;

    /// <summary>Returns the include blocks that a pass program receives, in Unity order.</summary>
    public static List<ShaderLabProgramBlock> GetIncludeBlocks(ShaderLabDocument document, ShaderLabSubShader subShader, ShaderLabPass pass)
    {
        ShaderLabProgramLanguage language = pass.Program?.Language ?? ShaderLabProgramLanguage.Cg;
        List<ShaderLabProgramBlock> blocks = [];
        AddMatching(blocks, document.IncludeBlocks, language);
        AddMatching(blocks, subShader.IncludeBlocks, language);
        AddMatching(blocks, pass.IncludeBlocks, language);
        return blocks;
    }

    /// <summary>Assembles one translation unit.</summary>
    /// <param name="document">The parsed shader.</param>
    /// <param name="includeBlocks">The include blocks from <see cref="GetIncludeBlocks"/>.</param>
    /// <param name="program">The pass program block.</param>
    /// <param name="stage">The stage being compiled.</param>
    /// <param name="entryPoint">The entry point function of the stage.</param>
    /// <param name="passKind">The engine use of the pass.</param>
    /// <param name="target">The shader model times ten.</param>
    /// <param name="keywords">The selected keywords.</param>
    public static string Assemble(
        ShaderLabDocument document,
        IReadOnlyList<ShaderLabProgramBlock> includeBlocks,
        ShaderLabProgramBlock program,
        ShaderProgramStage stage,
        string entryPoint,
        EnginePassKind passKind,
        int target,
        IReadOnlyList<string> keywords)
    {
        string path = document.SourcePath.Replace('\\', '/');
        StringBuilder builder = new(program.Code.Length + 4096);
        builder.Append("// Generated by the engine shader translator from ").Append(path).Append(". Do not edit.\n");
        builder.Append("#define XR_UNITY_TRANSLATION 1\n");
        builder.Append("#define SHADER_API_GLCORE 1\n");
        builder.Append("#define SHADER_TARGET ").Append(target).Append('\n');
        builder.Append("#define UNITY_VERSION ").Append(UnityVersion).Append('\n');
        builder.Append("#define ").Append(GetStageDefine(stage)).Append(" 1\n");
        string passDefine = GetPassDefine(passKind);
        builder.Append("#define ").Append(passDefine).Append(" 1\n");
        HashSet<string> defined = new(StringComparer.Ordinal) { passDefine };
        foreach (string keyword in keywords)
        {
            // A shader can declare a pass define as a keyword. Define each name one time only.
            if (defined.Add(keyword))
                builder.Append("#define ").Append(keyword).Append(" 1\n");
        }

        // Unity compiles every program with the legacy FXC rules, which allow implicit truncation.
        builder.Append("#include \"HLSLLegacyConversions.cginc\"\n");
        if (program.Language == ShaderLabProgramLanguage.Cg)
        {
            // Unity adds these two files to every CGPROGRAM block.
            builder.Append("#include \"HLSLSupport.cginc\"\n");
            builder.Append("#include \"UnityShaderVariables.cginc\"\n");
        }

        foreach (ShaderLabProgramBlock block in includeBlocks)
            AppendBlock(builder, path, block, stage, entryPoint);
        AppendBlock(builder, path, program, stage, entryPoint);
        return builder.ToString();
    }

    private static void AddMatching(List<ShaderLabProgramBlock> target, IReadOnlyList<ShaderLabProgramBlock> source, ShaderLabProgramLanguage language)
    {
        foreach (ShaderLabProgramBlock block in source)
            if (block.Language == language)
                target.Add(block);
    }

    private static void AppendBlock(StringBuilder builder, string path, ShaderLabProgramBlock block, ShaderProgramStage stage, string entryPoint)
    {
        string code = stage == ShaderProgramStage.Fragment ? RewriteFrontFacing(block.Code, entryPoint) : block.Code;
        builder.Append("#line ").Append(block.FirstLine).Append(" \"").Append(path).Append("\"\n");
        foreach (ReadOnlySpan<char> line in code.AsSpan().EnumerateLines())
        {
            ReadOnlySpan<char> trimmed = line.TrimStart();
            if (trimmed.StartsWith("#"))
            {
                ReadOnlySpan<char> directive = trimmed[1..].TrimStart();
                if (directive.StartsWith("pragma") && (directive.Length == 6 || char.IsWhiteSpace(directive[6])))
                {
                    builder.Append('\n');
                    continue;
                }

                if (directive.StartsWith("include_with_pragmas"))
                {
                    builder.Append("#include").Append(directive["include_with_pragmas".Length..]).Append('\n');
                    continue;
                }
            }

            builder.Append(line).Append('\n');
        }
    }

    /// <summary>
    /// Rewrites a <c>VFACE</c> parameter of the fragment entry point to the front-facing system value.
    /// </summary>
    /// <remarks>
    /// Unity gives <c>VFACE</c> as a float: positive for front faces and negative for back faces.
    /// The system value is a bool, which converts to 1 or 0, so code such as <c>normal * facing</c> or
    /// <c>facing &lt; 0</c> would break. The rewrite declares the original name as a float with values 1 and -1.
    /// It keeps the line count, so line directives stay correct.
    /// </remarks>
    public static string RewriteFrontFacing(string code, string entryPoint)
    {
        Regex signature = new($@"\b{Regex.Escape(entryPoint)}\s*\((?<parameters>[^)]*)\)", RegexOptions.CultureInvariant);
        Match match = signature.Match(code);
        while (match.Success)
        {
            Group parameters = match.Groups["parameters"];
            Match face = FrontFacingParameterPattern().Match(parameters.Value);
            int bodyStart = code.IndexOf('{', match.Index + match.Length);
            int statementEnd = code.IndexOf(';', match.Index + match.Length);
            bool isDefinition = bodyStart >= 0 && (statementEnd < 0 || bodyStart < statementEnd);
            if (face.Success && isDefinition)
            {
                string name = face.Groups["name"].Value;
                string rewrittenParameters = parameters.Value[..face.Index] +
                    $"bool {name}_xrFrontFacing : SV_IsFrontFace" + parameters.Value[(face.Index + face.Length)..];
                string declaration = $" float {name} = {name}_xrFrontFacing ? 1.0 : -1.0;";
                return code[..parameters.Index] + rewrittenParameters + code[(parameters.Index + parameters.Length)..bodyStart] +
                    "{" + declaration + code[(bodyStart + 1)..];
            }

            match = match.NextMatch();
        }

        return code;
    }

    [GeneratedRegex(@"(?:float|half|fixed|min16float|int)\s+(?<name>\w+)\s*:\s*VFACE\b", RegexOptions.CultureInvariant)]
    private static partial Regex FrontFacingParameterPattern();

    private static string GetStageDefine(ShaderProgramStage stage)
        => stage switch
        {
            ShaderProgramStage.Vertex => "SHADER_STAGE_VERTEX",
            ShaderProgramStage.Hull => "SHADER_STAGE_HULL",
            ShaderProgramStage.Domain => "SHADER_STAGE_DOMAIN",
            ShaderProgramStage.Geometry => "SHADER_STAGE_GEOMETRY",
            ShaderProgramStage.Fragment => "SHADER_STAGE_FRAGMENT",
            _ => throw new ArgumentOutOfRangeException(nameof(stage)),
        };

    private static string GetPassDefine(EnginePassKind passKind)
        => passKind switch
        {
            EnginePassKind.Unlit => "UNITY_PASS_ALWAYS",
            EnginePassKind.ForwardBase => "UNITY_PASS_FORWARDBASE",
            EnginePassKind.ForwardAdd => "UNITY_PASS_FORWARDADD",
            EnginePassKind.ShadowCaster => "UNITY_PASS_SHADOWCASTER",
            _ => throw new ArgumentOutOfRangeException(nameof(passKind)),
        };
}
