    string ProgramName,
    ulong Hash,
    ulong PreparedHash,
    ulong EffectiveSourceHash,
    uint ProgramId,
    uint ReplacementProgramId,
    uint SharedLinkedProgramId,
    int SharedLinkedProgramReferenceCount,
