namespace XREngine.Rendering.Models
{
    /// <summary>The flags of one LOD descriptor in a cooked <see cref="SubMesh"/>.</summary>
    [Flags]
    public enum ESubMeshLodFlags : uint
    {
        /// <summary>No flag.</summary>
        None = 0,

        /// <summary>The import made the LOD with automatic simplification.</summary>
        IsAutoGenerated = 1u << 0,

        /// <summary>The payload of the LOD is inline in the cooked sub-mesh. Only the coarsest LOD is inline.</summary>
        IsInline = 1u << 1,

        /// <summary>The LOD mesh has bone influences.</summary>
        HasSkinning = 1u << 2,

        /// <summary>The LOD mesh has blendshapes.</summary>
        HasBlendshapes = 1u << 3,

        /// <summary>The cook removed the blendshape data from the payload. The name hash still describes the names.</summary>
        BlendshapesStripped = 1u << 4,
    }
}
