using System;
using System.Collections.Concurrent;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Engine.Diagnostics;

/// <summary>Resolves checked source contracts and explicit trust boundaries per compilation.</summary>
internal sealed class HotPathContracts
{
    private readonly Compilation _compilation;
    private readonly INamedTypeSymbol _marker;
    private readonly INamedTypeSymbol? _trusted;
    private readonly INamedTypeSymbol? _span;
    private readonly INamedTypeSymbol? _readOnlySpan;
    private readonly AnalyzerConfigOptionsProvider _options;
    private readonly ConcurrentDictionary<IMethodSymbol, bool> _checked = new(SymbolEqualityComparer.Default);
    private readonly ConcurrentDictionary<INamedTypeSymbol, bool> _initialization = new(SymbolEqualityComparer.Default);

    public HotPathContracts(Compilation compilation, INamedTypeSymbol marker, AnalyzerConfigOptionsProvider options)
    {
        _compilation = compilation;
        _marker = marker;
        _trusted = compilation.GetTypeByMetadataName("Engine.Diagnostics.HotPathTrustedAttribute");
        _span = compilation.GetTypeByMetadataName("System.Span`1");
        _readOnlySpan = compilation.GetTypeByMetadataName("System.ReadOnlySpan`1");
        _options = options;
    }

    public bool IsTrusted(IMethodSymbol method)
    {
        method = (method.ReducedFrom ?? method).OriginalDefinition;
        if (HasMarker(method))
            return false;
        foreach (AttributeData attribute in method.GetAttributes())
            if (SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, _trusted) &&
                attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is string reason &&
                !string.IsNullOrWhiteSpace(reason))
                return true;
        return false;
    }

    public bool IsChecked(IMethodSymbol method, CancellationToken cancellationToken)
    {
        method = (method.ReducedFrom ?? method).OriginalDefinition;
        method = method.PartialImplementationPart ?? method;
        if (_checked.TryGetValue(method, out bool result))
            return result;
        result = IsCheckedSource(method, cancellationToken);
        _checked.TryAdd(method, result);
        return result;
    }

    private bool IsCheckedSource(IMethodSymbol method, CancellationToken cancellationToken)
    {
        if (method.IsExtern || method.IsAbstract ||
            !SymbolEqualityComparer.Default.Equals(method.ContainingAssembly, _compilation.Assembly))
            return false;

        bool marked = HasMarker(method);
        if (method.MethodKind == MethodKind.LocalFunction)
        {
            if (!method.IsStatic)
                return false;
            for (ISymbol? owner = method.ContainingSymbol; !marked && owner is IMethodSymbol parent; owner = parent.ContainingSymbol)
                marked = HasMarker(parent);
        }
        if (!marked)
            return false;

        foreach (SyntaxReference reference in method.DeclaringSyntaxReferences)
        {
            cancellationToken.ThrowIfCancellationRequested();
            SyntaxNode syntax = reference.GetSyntax(cancellationToken);
            bool hasBody = syntax switch
            {
                BaseMethodDeclarationSyntax declaration => declaration.Body is not null || declaration.ExpressionBody is not null,
                AccessorDeclarationSyntax accessor => accessor.Body is not null || accessor.ExpressionBody is not null,
                LocalFunctionStatementSyntax local => local.Body is not null || local.ExpressionBody is not null,
                _ => false
            };
            if (hasBody && !IsGenerated(syntax.SyntaxTree, method, cancellationToken))
                return true;
        }
        return false;
    }

    private bool IsGenerated(SyntaxTree tree, IMethodSymbol method, CancellationToken cancellationToken)
    {
        if (_options.GetOptions(tree).TryGetValue("generated_code", out string? generated))
            return string.Equals(generated, "true", StringComparison.OrdinalIgnoreCase);
        string path = tree.FilePath;
        if (path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) ||
            path.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase) ||
            path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase) ||
            path.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase))
            return true;
        SyntaxNode root = tree.GetRoot(cancellationToken);
        foreach (SyntaxTrivia trivia in root.GetLeadingTrivia())
            if (trivia.ToString().IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0)
                return true;
        for (ISymbol? symbol = method; symbol is not null; symbol = symbol.ContainingType)
            foreach (AttributeData attribute in symbol.GetAttributes())
                if (attribute.AttributeClass?.ToDisplayString() is "System.CodeDom.Compiler.GeneratedCodeAttribute" or
                    "System.Runtime.CompilerServices.CompilerGeneratedAttribute")
                    return true;
        return false;
    }

    private bool HasMarker(IMethodSymbol method)
    {
        foreach (AttributeData attribute in method.GetAttributes())
            if (SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, _marker))
                return true;
        return false;
    }

    public bool HasCheckedInitialization(INamedTypeSymbol type, CancellationToken cancellationToken)
    {
        type = type.OriginalDefinition;
        if (_initialization.TryGetValue(type, out bool result))
            return result;
        result = true;
        foreach (IMethodSymbol constructor in type.StaticConstructors)
            if (!constructor.IsImplicitlyDeclared && !IsChecked(constructor, cancellationToken))
                result = false;
        foreach (ISymbol member in type.GetMembers())
        {
            if (!member.IsStatic || member is IFieldSymbol { IsConst: true })
                continue;
            if (HasInitializer(member, cancellationToken))
                result = false;
        }
        _initialization.TryAdd(type, result);
        return result;
    }

    public static bool HasInitializer(ISymbol member, CancellationToken cancellationToken)
    {
        foreach (SyntaxReference reference in member.DeclaringSyntaxReferences)
            if (reference.GetSyntax(cancellationToken) is VariableDeclaratorSyntax { Initializer: not null } or
                PropertyDeclarationSyntax { Initializer: not null })
                return true;
        return false;
    }

    public bool IsSpan(ITypeSymbol? type)
        => type is INamedTypeSymbol named &&
            !SymbolEqualityComparer.Default.Equals(named.ContainingAssembly, _compilation.Assembly) &&
            (SymbolEqualityComparer.Default.Equals(named.OriginalDefinition, _span) ||
             SymbolEqualityComparer.Default.Equals(named.OriginalDefinition, _readOnlySpan));

    public bool IsIntrinsic(IMethodSymbol method)
    {
        if (SymbolEqualityComparer.Default.Equals(method.ContainingAssembly, _compilation.Assembly))
            return false;
        if (method.ContainingType.SpecialType == SpecialType.System_Object && method.MethodKind == MethodKind.Constructor && method.Parameters.Length == 0)
            return true;
        if (method.ContainingType.SpecialType == SpecialType.System_String && method.MethodKind == MethodKind.PropertyGet)
            return method.Name is "get_Length" or "get_Chars";
        if (IsSpan(method.ContainingType) && method.MethodKind == MethodKind.PropertyGet)
            return method.Name is "get_Length" or "get_IsEmpty" or "get_Item";
        return false;
    }
}
